source('04_demand_forecast.R')
dataset <- load_sales_data('bikes_database.db')
selected <- default_selection(dataset)
monthly <- monthly_sales(filter_sales(dataset$sales, selected), dataset$coverage, selected$date_range)
result <- forecast_analysis(monthly, selected$horizon)
cat('Synthetic seed:', dataset$metadata$seed, '\n')
cat('Training:', as.character(result$train_start), 'to', as.character(result$train_end), '\n')
cat('Heldout:', as.character(result$test_start), 'to', as.character(result$test_end), '(6 complete months)\n')
cat('Units: USD per month. Interval nominal level:', result$interval_level, '\n')
print(result$metrics, row.names = FALSE)
cat('Validation values:\n'); print(result$validation, row.names = FALSE)
cat('Future after all-history refit:\n'); print(result$future, row.names = FALSE)
cat('Comparison drivers:\n'); print(compare_periods(dataset, selected)$components, row.names = FALSE)
cat('Synthetic accuracy says nothing about real retail performance.\n')
